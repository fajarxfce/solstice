// Spike S1, Dart half: what does a view diff cost to decode?
//
// Plan §5.1's kill criterion, verbatim: an initial 1000-row view must decode in
// under 5ms and a 5-row delta in under 100µs, in Dart *and* Kotlin, on a
// mid-range phone. Miss it and the byte ABI as designed is wrong, and the
// fallback is a columnar diff with generated zero-copy accessors — a different
// `.proto` and a different shape for everything above it.
//
// Which is the whole reason this runs before `flutter_rust_bridge` is wired up.
// The bridging is mechanical; it is also the work that would be thrown away.
//
// Run it with `./run.sh` from this directory.

import 'dart:io';
import 'dart:typed_data';

import 'package:s1_decode/gen/solstice/v1/view.pb.dart';

/// Enough repetitions that the JIT has finished deciding what this code is.
const warmup = 200;
const reps = 500;

void main(List<String> args) {
  final dir = args.isEmpty ? '../fixtures' : args[0];
  final view = _read('$dir/view-1000.bin');
  final delta = _read('$dir/delta-5.bin');

  print('# spike S1 — Dart');
  print('');
  print('Dart ${Platform.version.split(' ').first} · ${Platform.operatingSystem}');
  print('');
  print('| payload | bytes | rows | decode (best) | decode (p50) | budget | |');
  print('|---|---|---|---|---|---|---|');

  _measure('initial view', view, 1000, Duration(milliseconds: 5));
  _measure('5-row delta', delta, 5, Duration(microseconds: 100));

  print('');
  _traverse(view);
}

Uint8List _read(String path) {
  final f = File(path);
  if (!f.existsSync()) {
    stderr.writeln(
      'missing $path — run `cargo run --release -p solstice-bench --bin s1-fixture` first',
    );
    exit(2);
  }
  return f.readAsBytesSync();
}

void _measure(String label, Uint8List bytes, int rows, Duration budget) {
  for (var i = 0; i < warmup; i++) {
    _sink(ViewDelta.fromBuffer(bytes));
  }

  final samples = <int>[];
  for (var i = 0; i < reps; i++) {
    final sw = Stopwatch()..start();
    final decoded = ViewDelta.fromBuffer(bytes);
    sw.stop();
    // Touch the result. A decode whose output is discarded is a decode the
    // compiler is entitled to shrink, and `fromBuffer` is eager but the
    // sub-message accessors are where the work actually lands.
    _sink(decoded);
    samples.add(sw.elapsedMicroseconds);
  }
  samples.sort();

  final best = samples.first;
  final p50 = samples[samples.length ~/ 2];
  final pass = best <= budget.inMicroseconds;
  print(
    '| $label | ${_bytes(bytes.length)} | $rows | ${_us(best)} | ${_us(p50)} '
    '| < ${_us(budget.inMicroseconds)} | ${pass ? "PASS" : "FAIL"} |',
  );
}

/// Verifies the payload as well as timing it.
///
/// This is the cross-check the hand-written Rust encoder does not have on its
/// own: code generated by `protoc` from the normative `.proto`, in a different
/// language, reading bytes Rust produced. If the numbers below are right, the
/// two agree about the wire format.
///
/// It asserts rather than prints. The fixture is generated from a fixed seed, so
/// these counts are constants, and an encoder that drifts from the `.proto`
/// would otherwise show up as a line of output nobody reads. Exit code 1 makes
/// it a CI failure.
void _traverse(Uint8List bytes) {
  final d = ViewDelta.fromBuffer(bytes);
  var parents = 0, children = 0, scalars = 0, nulls = 0;

  for (final change in d.changes) {
    if (!change.hasAdded()) continue;
    parents++;
    for (final v in change.added.row.values) {
      if (v.hasRows()) {
        for (final child in v.rows.rows) {
          children++;
          scalars += child.values.length;
        }
      } else {
        scalars++;
        if (v.whichKind() == Value_Kind.notSet) nulls++;
      }
    }
  }

  print(
    'cross-check: $parents parents · $children children · $scalars scalars '
    '· $nulls nulls · sub ${d.subId} v${d.version}',
  );
  final first = d.changes.first.added.row;
  print(
    'first row: id=${first.values[0].integer} title="${first.values[4].text}"',
  );

  // 1000 parents × 6 columns, 3000 children × 5 columns.
  final failures = <String>[
    if (parents != 1000) 'parents: $parents != 1000',
    if (children != 3000) 'children: $children != 3000',
    if (scalars != 21000) 'scalars: $scalars != 21000',
    if (d.subId != 1) 'sub_id: ${d.subId} != 1',
    if (d.version != 1) 'version: ${d.version} != 1',
    if (first.values[0].integer.toInt() != 19) 'first id: != 19',
  ];
  if (failures.isNotEmpty) {
    stderr.writeln('cross-check FAILED — ${failures.join('; ')}');
    stderr.writeln(
      'the Rust encoder and the generated Dart decoder disagree about the wire '
      'format, or the fixture was regenerated with different parameters',
    );
    exit(1);
  }
}

void _sink(ViewDelta d) {
  if (d.changes.isEmpty) throw StateError('empty delta');
}

String _us(int us) =>
    us >= 1000 ? '${(us / 1000).toStringAsFixed(2)}ms' : '${us}µs';

String _bytes(int n) => n >= 1024
    ? '${(n / 1024).toStringAsFixed(1)} KB'
    : '$n B';
